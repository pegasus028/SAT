#!/usr/bin/env node
/* C-3 build: tools/c3-src-papers.js + tools/c3-src-adaptive.js  →  data/tests.js (window.TESTS, SPEC §4.7).
   The key positions are planned here, per paper/module, before any option is placed: each position ~25%,
   never three identical in a row. In the sources o[0] is always the key; this script puts it at the planned
   slot and fills the other slots with the distractors in their written order (whyEach follows the options).
   Run: node tools/c3-build.js   then   node tools/c3-validate.js */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const P = require('./c3-src-papers.js'), A = require('./c3-src-adaptive.js');

const SEQ = {
  placement:     [1,3,0,2,3,0,2,1,0,1,3,2,2,0,1,3],
  stage:         [2,0,3,1,1,3,0,2,0,2,3,1,3,1,2,0,0,2,1,3],
  final:         [3,1,0,2,0,3,2,1,1,2,3,0,2,0,1,3,3,1,0,2],
  'a1.m1':       [2,0,3,1,0,2,1,3,3,0,1,2],
  'a1.m2easy':   [1,3,0,2,2,0,3,1,0,3,2,1],
  'a1.m2hard':   [3,1,2,0,1,3,0,2,0,1,3,2],
  'a2.m1':       [0,2,1,3,3,1,2,0,2,3,0,1],
  'a2.m2easy':   [2,3,0,1,0,2,3,1,1,2,0,3],
  'a2.m2hard':   [1,0,2,3,2,1,0,3,0,3,1,2]
};
const DOMAIN = { lit: 'literature', hist: 'history/social studies', hum: 'humanities', sci: 'science' };
const PROMPT = {
  wic: 'Which choice completes the text with the most logical and precise word or phrase?',
  transition: 'Which choice completes the text with the most logical transition?'
};

function place(arr, k) { const out = new Array(4); out[k] = arr[0]; let j = 1; for (let i = 0; i < 4; i++) if (i !== k) out[i] = arr[j++]; return out; }
function build(src, seqName) {
  const seq = SEQ[seqName];
  if (!seq || seq.length !== src.length) throw new Error(seqName + ': sequence length ' + (seq && seq.length) + ' vs items ' + src.length);
  return src.map((s, i) => {
    const k = seq[i];
    const e = s.e.slice(); if (e[0] == null) e[0] = 'Right. ' + s.why;
    return {
      id: s.id, type: s.t, domain: DOMAIN[s.d] || s.d,
      passage: s.p,
      prompt: s.t === 'meaning' ? 'As used in the text, what does the word “' + s.mw + '” most nearly mean?' : PROMPT[s.t],
      options: place(s.o, k), answer: k,
      hint: s.h, why: s.why, whyEach: place(e, k),
      word: s.w == null ? null : s.w, field: s.f, skill: s.t, level: s.lv
    };
  });
}

const TESTS = {
  papers: [
    { id: 'placement', kind: 'placement', title: 'Placement check', minutes: 15,
      blurb: 'Two questions on each of the eight fields. Your misses set your study route in the Stages tab.',
      items: build(P.placement, 'placement') },
    { id: 'stage-vocab', kind: 'check', title: 'Stage check: SAT words', minutes: 20,
      blurb: 'Twenty questions across all 30 high-value SAT words, in the order of the real section: Words in Context first, Transitions last.',
      items: build(P.stage, 'stage') },
    { id: 'final', kind: 'final', title: 'Final word check', minutes: 20,
      blurb: 'Twenty new questions, a step harder than the stage check, with two ‘most nearly means’ items and three transitions.',
      items: build(P.final, 'final') }
  ],
  adaptive: [
    { id: 'adaptive-1', title: 'Words in Context: practice module set A', note: 'SAT-style practice (format unofficial)',
      m1: { minutes: 14, items: build(A.a1.m1, 'a1.m1') }, cut: 8,
      m2easy: { minutes: 14, items: build(A.a1.m2easy, 'a1.m2easy') },
      m2hard: { minutes: 14, items: build(A.a1.m2hard, 'a1.m2hard') } },
    { id: 'adaptive-2', title: 'Words in Context: practice module set B', note: 'SAT-style practice (format unofficial)',
      m1: { minutes: 14, items: build(A.a2.m1, 'a2.m1') }, cut: 8,
      m2easy: { minutes: 14, items: build(A.a2.m2easy, 'a2.m2easy') },
      m2hard: { minutes: 14, items: build(A.a2.m2hard, 'a2.m2hard') } }
  ]
};

const head = '/* ============================================================\n' +
  '   SAT Studio — tests.js: papers and adaptive practice module sets (C-3, SPEC §4.7)\n' +
  '   GENERATED by tools/c3-build.js from tools/c3-src-papers.js and tools/c3-src-adaptive.js.\n' +
  '   Edit the sources, then run  node tools/c3-build.js && node tools/c3-validate.js\n' +
  '   All passages and items are original (no College Board text, no recalled items).\n' +
  '   SAT-style practice: the format of these sets is unofficial. Text in *asterisks* shows in bold.\n' +
  '   Tests stay silent (no read-aloud): audio would give answers away.\n' +
  '   ============================================================ */\n';
fs.writeFileSync(path.join(ROOT, 'data', 'tests.js'), head + 'window.TESTS = ' + JSON.stringify(TESTS, null, 1) + ';\n');
const n = TESTS.papers.reduce((a, p) => a + p.items.length, 0) + TESTS.adaptive.reduce((a, s) => a + s.m1.items.length + s.m2easy.items.length + s.m2hard.items.length, 0);
console.log('data/tests.js written: ' + n + ' items');
