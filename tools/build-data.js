/* Generates data/words.js, data/patterns.js and data/fields.js from src/sat-data-pack.json.
   Never hand-edit those three files: edit the pack (owned by the research chat), then run
   node tools/build-data.js. Thai notes are dropped (T.Chris, 25 Nov 2026: no Thai text). */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const pack = JSON.parse(fs.readFileSync(path.join(root, 'src/sat-data-pack.json'), 'utf8'));
const head = (file, what) => `/* ============================================================
   SAT Studio — ${file}: ${what}
   GENERATED by tools/build-data.js from src/sat-data-pack.json (data pack v${pack.meta.version}, ${pack.meta.date}).
   Do not edit by hand: change the pack, then run  node tools/build-data.js
   Importance = learning value, not a prediction that a word appears.
   cefr: null displays as "not graded". Text in *asterisks* shows in bold.
   ============================================================ */\n`;
const words = pack.words.map(w => { const o = Object.assign({}, w); delete o.thai; return o; });
const ids = new Set(words.map(w => w.id));
words.forEach(w => (w.related || []).forEach(r => { if (!ids.has(r)) throw new Error(w.id + ' related ' + r); }));
pack.patterns.forEach(p => (p.items || []).forEach(r => { if (!ids.has(r)) throw new Error(p.id + ' item ' + r); }));
fs.writeFileSync(path.join(root, 'data/words.js'), head('words.js', 'the 30 high-value SAT words and phrases') +
  'window.SAT_META = ' + JSON.stringify(pack.meta, null, 1) + ';\nwindow.WORDS = ' + JSON.stringify(words, null, 1) + ';\n');
fs.writeFileSync(path.join(root, 'data/patterns.js'), head('patterns.js', 'the 10 pattern cards (text only; play data is in data/pattern-play.js)') +
  'window.PATTERNS = ' + JSON.stringify(pack.patterns, null, 1) + ';\n');
fs.writeFileSync(path.join(root, 'data/fields.js'), head('fields.js', 'the 8 meaning fields and the 16 runners-up') +
  'window.FIELDS = ' + JSON.stringify(pack.fields, null, 1) + ';\nwindow.RUNNERS_UP = ' + JSON.stringify(pack.runners_up, null, 1) + ';\n');
console.log('words', words.length, 'patterns', pack.patterns.length, 'fields', pack.fields.length);
